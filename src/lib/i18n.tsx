type I18nContextValue = {
  lang: AppLanguage;
  locale: string;
  setLang: (lang: AppLanguage) => void;
  toggleLang: () => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function detectLanguage(): AppLanguage {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === "fr" || stored === "en") return stored;
  return window.navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function AppI18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<AppLanguage>("en");

  useEffect(() => {
    const initial = detectLanguage();
    setLangState(initial);
    document.documentElement.lang = initial === "fr" ? "fr-CA" : "en";
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "fr" ? "fr-CA" : "en";
  }, [lang]);

  const setLang = (next: AppLanguage) => {
    setLangState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  };

  const value = useMemo<I18nContextValue>(() => ({
    lang,
    locale: lang === "fr" ? "fr-CA" : "en-US",
    setLang,
    toggleLang: () => setLang(lang === "fr" ? "en" : "fr"),
    t: (key, vars) => {
      let value = translations[lang][key] ?? translations.en[key] ?? key;
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          value = value.replaceAll("{" + name + "}", String(replacement));
        }
      }
      return value;
    },
  }), [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useAppI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useAppI18n must be used inside AppI18nProvider");
  return context;
}
